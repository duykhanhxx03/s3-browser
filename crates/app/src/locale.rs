#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn english_is_the_default_language() {
        assert_eq!(Language::default(), Language::English);
    }

    #[test]
    fn every_language_has_a_stable_code_and_name() {
        for language in Language::ALL {
            assert!(!language.code().is_empty());
            assert!(!language.native_name().is_empty());
        }
    }

    #[test]
    fn untranslated_languages_fall_back_to_english() {
        assert_eq!(
            translated(Language::Japanese, "command.share"),
            Some("Share / presigned URL")
        );
    }

    #[test]
    fn popular_languages_translate_core_navigation() {
        for language in Language::ALL {
            assert_ne!(translated(language, "settings.title"), None);
            assert_ne!(translated(language, "nav.settings"), None);
            assert_ne!(translated(language, "form.test_connection"), None);
        }
        assert_eq!(
            translated(Language::Spanish, "settings.title"),
            Some("Ajustes")
        );
        assert_eq!(
            translated(Language::French, "settings.title"),
            Some("Réglages")
        );
        assert_eq!(
            translated(Language::ChineseSimplified, "settings.title"),
            Some("设置")
        );
    }

    #[test]
    fn credential_forms_use_storage_terms_precisely() {
        assert_eq!(
            translated(Language::English, "form.new_profile"),
            Some("New connection")
        );
        assert_eq!(
            translated(Language::English, "form.probe_bucket"),
            Some("Bucket to verify")
        );
        assert_eq!(
            translated(Language::English, "form.secret_key"),
            Some("Secret access key")
        );
        assert_eq!(
            translated(Language::Vietnamese, "form.provider"),
            Some("Nhà cung cấp S3")
        );
    }
}
