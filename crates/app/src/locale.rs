//! User-facing text and language selection.
//!
//! The app started life with Vietnamese strings in place. This module gives new
//! UI text one home and makes English the default, while leaving technical S3
//! terms such as bucket, object, endpoint and access key in their standard
//! spelling. Missing translations intentionally fall back to English.

use std::sync::atomic::{AtomicU8, Ordering};

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Language {
    #[default]
    English,
    Vietnamese,
    Spanish,
    French,
    German,
    Japanese,
    Korean,
    ChineseSimplified,
    Portuguese,
    Indonesian,
}

impl Language {
    pub const ALL: [Language; 10] = [
        Language::English,
        Language::Vietnamese,
        Language::Spanish,
        Language::French,
        Language::German,
        Language::Japanese,
        Language::Korean,
        Language::ChineseSimplified,
        Language::Portuguese,
        Language::Indonesian,
    ];

    fn index(self) -> u8 {
        match self {
            Language::English => 0,
            Language::Vietnamese => 1,
            Language::Spanish => 2,
            Language::French => 3,
            Language::German => 4,
            Language::Japanese => 5,
            Language::Korean => 6,
            Language::ChineseSimplified => 7,
            Language::Portuguese => 8,
            Language::Indonesian => 9,
        }
    }

    fn from_index(index: u8) -> Self {
        Self::ALL
            .get(index as usize)
            .copied()
            .unwrap_or(Language::English)
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Language::English => "English",
            Language::Vietnamese => "Tiếng Việt",
            Language::Spanish => "Español",
            Language::French => "Français",
            Language::German => "Deutsch",
            Language::Japanese => "日本語",
            Language::Korean => "한국어",
            Language::ChineseSimplified => "简体中文",
            Language::Portuguese => "Português",
            Language::Indonesian => "Bahasa Indonesia",
        }
    }

    #[cfg(test)]
    pub fn code(self) -> &'static str {
        match self {
            Language::English => "en",
            Language::Vietnamese => "vi",
            Language::Spanish => "es",
            Language::French => "fr",
            Language::German => "de",
            Language::Japanese => "ja",
            Language::Korean => "ko",
            Language::ChineseSimplified => "zh-Hans",
            Language::Portuguese => "pt",
            Language::Indonesian => "id",
        }
    }
}

static LANGUAGE: AtomicU8 = AtomicU8::new(0);

pub fn set_language(language: Language) {
    LANGUAGE.store(language.index(), Ordering::Relaxed);
}

pub fn language() -> Language {
    Language::from_index(LANGUAGE.load(Ordering::Relaxed))
}

pub fn text(key: &str) -> &'static str {
    translated(language(), key).unwrap_or_else(|| english(key))
}

fn english(key: &str) -> &'static str {
    translated(Language::English, key).unwrap_or("Missing text")
}

fn translated(language: Language, key: &str) -> Option<&'static str> {
    match language {
        Language::English => en(key),
        Language::Vietnamese => vi(key),
        Language::Spanish => es(key),
        Language::French => fr(key),
        Language::German => de(key),
        Language::Japanese => ja(key),
        Language::Korean => ko(key),
        Language::ChineseSimplified => zh_hans(key),
        Language::Portuguese => pt(key),
        Language::Indonesian => id(key),
    }
}

